#!/bin/sh
# Set these dotfiles up on this machine. Safe to re-run.
#  1. Symlink each entry of .config/ into ~/.config (anything already there is moved aside first)
#  2. Link the systemd user units shipped in the repo
#  3. Remove links left dangling by configs that were dropped from the repo
#  4. Write hypr/local.lua from the detected hardware, unless it already exists
#  5. Report missing packages and per-machine bits still to do
set -eu

repo=$(cd "$(dirname "$0")" && pwd)
config="${XDG_CONFIG_HOME:-$HOME/.config}"

# Move $1 out of the way: <name>.pre-dotfiles, or with a timestamp if that's taken
backup() {
    b="$1.pre-dotfiles"
    if [ -e "$b" ] || [ -L "$b" ]; then b="$b.$(date +%Y%m%d-%H%M%S)"; fi
    mv "$1" "$b"
    echo "backup  $1 -> $b"
}

link() {
    src=$1 dst=$2
    if [ -L "$dst" ] && [ "$(readlink "$dst")" = "$src" ]; then
        echo "ok      $dst"
        return
    fi
    if [ -e "$dst" ] || [ -L "$dst" ]; then backup "$dst"; fi
    mkdir -p "$(dirname "$dst")"
    ln -s "$src" "$dst"
    echo "link    $dst -> $src"
}

# --- 1. Configs. Top-level entries are linked whole, except xdg-desktop-portal, which is linked
# per file because other packages may drop their own portal configs next to ours.
for entry in "$repo"/.config/*; do
    name=$(basename "$entry")
    case "$name" in
    xdg-desktop-portal)
        for f in "$entry"/*; do link "$f" "$config/$name/$(basename "$f")"; done ;;
    *)
        link "$entry" "$config/$name" ;;
    esac
done

# --- 2. systemd user units (started from hypr/hyprland.lua)
for unit in "$repo"/.config/*/*.service; do
    [ -e "$unit" ] && link "$unit" "$config/systemd/user/$(basename "$unit")"
done
if command -v systemctl >/dev/null && systemctl --user daemon-reload 2>/dev/null; then :; fi

# --- 3. Dangling links into the repo (e.g. ~/.config/waybar after waybar was removed)
for l in "$config"/* "$config"/xdg-desktop-portal/* "$config"/systemd/user/*; do
    if [ -L "$l" ] && [ ! -e "$l" ]; then
        case "$(readlink "$l")" in
        "$repo"/*) rm "$l"; echo "prune   $l" ;;
        esac
    fi
done

# --- 4. Hardware detection
# GPU kernel drivers, one line per card (card1-DP-1 etc. are connectors, not cards)
drivers=$(for c in /sys/class/drm/card[0-9]*; do
    case "$c" in *-*) continue ;; esac
    sed -n 's/^DRIVER=//p' "$c/device/uevent" 2>/dev/null
done)
ngpus=$(printf '%s\n' "$drivers" | grep -c . || true)
has_nvidia=$(printf '%s\n' "$drivers" | grep -qx nvidia && echo yes || echo no)
others=$(printf '%s\n' "$drivers" | grep -vx nvidia | sort -u | tr '\n' ' ' | sed 's/ $//')
laptop=$(ls /sys/class/power_supply/BAT* >/dev/null 2>&1 && echo yes || echo no)

kb_layout=$(localectl status 2>/dev/null | sed -n 's/^ *X11 Layout: *//p')
kb_variant=$(localectl status 2>/dev/null | sed -n 's/^ *X11 Variant: *//p')

local_lua="$repo/.config/hypr/local.lua"
if [ -e "$local_lua" ]; then
    echo "ok      $local_lua (kept; delete it to regenerate)"
else
    {
        cat <<EOF
-- This machine only (not tracked by git). Generated by install.sh on $(date +%F); edit freely,
-- install.sh won't overwrite it. See "Per-machine settings" in the repo README.

-- Monitors without a rule here use their preferred mode (hyprland.lua). Add one per output, with
-- names from \`hyprctl monitors\`, e.g. for a refresh rate the monitor doesn't report as preferred:
-- hl.monitor({ output = "DP-1", mode = "2560x1440@165", position = "0x0", scale = 1 })

hl.config({
    input = {
        kb_layout  = "${kb_layout:-us}",
        kb_variant = "${kb_variant}",
EOF
        if [ "$laptop" = yes ]; then
            cat <<'EOF'
        touchpad = {
            natural_scroll = false,
            tap_to_click   = true,
        },
EOF
        fi
        cat <<'EOF'
    },
})
EOF
        if [ "$has_nvidia" = yes ] && [ -z "$others" ]; then
            cat <<'EOF'

-- NVIDIA (https://wiki.hypr.land/Nvidia/)
hl.env("LIBVA_DRIVER_NAME", "nvidia")
hl.env("__GLX_VENDOR_LIBRARY_NAME", "nvidia")
hl.env("NVD_BACKEND", "direct")
EOF
        elif [ "$has_nvidia" = yes ]; then
            cat <<EOF

-- Hybrid graphics ($others + nvidia): Hyprland renders on the integrated GPU so the NVIDIA card
-- can power down when idle; screens wired to the NVIDIA card still work. Run games and heavy apps
-- on it with \`prime-run <command>\` (package nvidia-prime); in Steam: prime-run %command%
EOF
        elif [ "$ngpus" -gt 1 ]; then
            cat <<EOF

-- Several GPUs ($others). Hyprland uses all of them; to keep it on one (e.g. the discrete card
-- your monitors are plugged into), give that card a stable name with a udev rule (README,
-- "Several GPUs") and point Hyprland at it:
-- hl.env("AQ_DRM_DEVICES", "/dev/dri/dgpu")
EOF
        fi
        cat <<'EOF'

-- Name shown in the bar's performance card when pci.ids only knows the chip family:
-- hl.env("QS_GPU_NAME", "Radeon RX 9070 XT")
EOF
    } > "$local_lua"
    echo "write   $local_lua"
fi

# --- 5. What's left
echo
missing=$(grep -v '^\s*\(#\|$\)' "$repo/packages.txt")
[ "$has_nvidia" = yes ] && missing="$missing nvidia-utils"
[ "$has_nvidia" = yes ] && [ -n "$others" ] && missing="$missing nvidia-prime"
# shellcheck disable=SC2086 # word splitting is the point
missing=$(pacman -T $missing 2>/dev/null | tr '\n' ' ' || true)
if [ -n "$missing" ]; then
    echo "Missing packages: sudo pacman -S --needed $missing"
fi

if [ ! -e "$repo/.config/hypr/wallpaper" ]; then
    echo "No wallpaper yet (hyprpaper, hyprlock): ln -s /path/to/image $repo/.config/hypr/wallpaper"
fi

if [ "$has_nvidia" = yes ] && ! grep -qs '^options nvidia_drm .*modeset=1' /etc/modprobe.d/*.conf &&
   ! grep -qs 'nvidia_drm.modeset=1' /proc/cmdline &&
   [ "$(cat /sys/module/nvidia_drm/parameters/modeset 2>/dev/null)" != Y ]; then
    echo "NVIDIA: kernel modesetting looks off; see https://wiki.hypr.land/Nvidia/"
fi

# Notification daemons are D-Bus activated; one that starts before Quickshell takes its place
for d in dunst mako swaync; do
    if command -v "$d" >/dev/null && [ "$(readlink "$config/systemd/user/$d.service" 2>/dev/null)" != /dev/null ]; then
        echo "$d is installed; mask it so Quickshell gets the notifications: systemctl --user mask $d"
    fi
done

echo "Done. Log in to Hyprland (or run: hyprctl reload && systemctl --user restart quickshell)."
